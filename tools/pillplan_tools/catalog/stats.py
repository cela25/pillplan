"""Catalog numbers for the LaTeX documentation, so the PDF graphs use the real data."""

from collections import Counter

from .models import Catalog


def area_counts(catalog: Catalog) -> list[tuple[str, int]]:
    """Drugs per therapeutic area, largest first, ties by name."""
    counts = Counter(drug.area.en for drug in catalog.drugs)
    return sorted(counts.items(), key=lambda item: (-item[1], item[0]))


def render_tex(catalog: Catalog) -> str:
    """TeX macros plus a pgf-pie data list for the documentation."""
    areas = area_counts(catalog)
    pie = ",\n  ".join(f"{count}/{_escape(area)}" for area, count in areas)
    with_limit = sum(1 for i in catalog.ingredients if i.usual_max_daily is not None)
    timing = sum(1 for d in catalog.drugs if d.best_times)
    classes = len({d.drug_class.en for d in catalog.drugs})
    return (
        "% Generated by pillplan_tools.catalog.build. Do not edit by hand.\n"
        f"\\newcommand{{\\CatalogDrugs}}{{{len(catalog.drugs)}}}\n"
        f"\\newcommand{{\\CatalogIngredients}}{{{len(catalog.ingredients)}}}\n"
        f"\\newcommand{{\\CatalogIngredientsWithLimit}}{{{with_limit}}}\n"
        f"\\newcommand{{\\CatalogClasses}}{{{classes}}}\n"
        f"\\newcommand{{\\CatalogAreas}}{{{len(areas)}}}\n"
        f"\\newcommand{{\\CatalogTimingRules}}{{{timing}}}\n"
        f"\\newcommand{{\\CatalogWarnings}}{{{len(catalog.warnings)}}}\n"
        f"\\newcommand{{\\CatalogAreaPie}}[1]{{\\pie[#1]{{\n  {pie}\n}}}}\n"
    )


def _escape(text: str) -> str:
    return text.replace("&", "\\&").replace("%", "\\%")
